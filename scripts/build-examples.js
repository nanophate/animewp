#!/usr/bin/env node
/**
 * Build the theme's example patterns from block trees (scripts/examples/*.js),
 * using WordPress's own serializer and the AnimeWP Blocks build, so every
 * example is valid block markup. Output: themes/animewp/examples/<slug>.php.
 *
 *   npm run build && node scripts/build-examples.js [--check]
 *
 * Needs the WordPress editor scripts from wp-env (npm run env:start) or
 * ANIMEWP_WP_DIR, like tests/serialization.
 */
'use strict';
const fs = require( 'node:fs' );
const path = require( 'node:path' );
const { ORIGIN, installWordPress, loadPlugin } = require( '../tests/serialization/env' );

const ROOT = path.resolve( __dirname, '..' );
const OUT = path.join( ROOT, 'themes/animewp/examples' );
// Two stand-ins for theme image URLs: core blocks store absolute URLs, while
// AnimeWP posters are always stored as site-relative paths.
const ASSET = 'animewp-theme-asset://images/';
const ASSET_PATH = '/wp-content/themes/animewp/assets/images/';
const check = process.argv.includes( '--check' );

const { window, wp } = installWordPress();
loadPlugin( path.join( ROOT, 'plugins/animewp-blocks' ), window );
const { createBlock, serialize, parse } = wp.blocks;

/** createBlock with attributes copied into the page realm; children may be omitted. */
function b( name, attributes = {}, inner = [] ) {
	if ( ! wp.blocks.getBlockType( name ) ) {
		throw new Error( 'Unknown block in example: ' + name );
	}
	return createBlock( name, window.JSON.parse( JSON.stringify( attributes ) ), inner );
}
const image = ( file ) => ASSET + file;
const poster = ( file ) => ASSET_PATH + file;

function requiredBlocks( blocks, found = new Set() ) {
	blocks.forEach( ( block ) => {
		if ( block.name.startsWith( 'animewp/' ) ) {
			found.add( block.name );
		}
		requiredBlocks( block.innerBlocks, found );
	} );
	return [ ...found ].sort();
}

function invalid( markup ) {
	const bad = [];
	const walk = ( blocks ) =>
		blocks.forEach( ( block ) => {
			if ( block.isValid === false ) {
				bad.push( block.name );
			}
			walk( block.innerBlocks );
		} );
	walk( parse( markup ) );
	return bad;
}

const header = ( example, requires ) =>
	[
		'<?php',
		'/**',
		' * Title: ' + example.title,
		' * Slug: animewp/' + example.slug,
		' * Categories: ' + example.categories.join( ', ' ),
		' * Description: ' + example.description,
		requires.length ? ' * Requires Blocks: ' + requires.join( ', ' ) : null,
		example.viewportWidth ? ' * Viewport Width: ' + example.viewportWidth : null,
		' *',
		' * Generated by scripts/build-examples.js from scripts/examples. Edit the source and rebuild.',
		' */',
		"if ( ! defined( 'ABSPATH' ) ) { exit; }",
		'?>',
	]
		.filter( ( line ) => line !== null )
		.join( '\n' );

const examples = fs
	.readdirSync( path.join( __dirname, 'examples' ) )
	.filter( ( file ) => file.endsWith( '.js' ) && ! file.startsWith( '_' ) )
	.sort()
	.flatMap( ( file ) => [].concat( require( path.join( __dirname, 'examples', file ) )( { b, image, poster } ) ) );

fs.mkdirSync( OUT, { recursive: true } );
const written = new Set();
let stale = 0;
for ( const example of examples ) {
	const blocks = [].concat( example.blocks );
	const markup = serialize( blocks );
	const problems = invalid( markup );
	if ( problems.length ) {
		throw new Error( example.slug + ': invalid blocks after re-parse: ' + problems.join( ', ' ) );
	}
	// Theme images are referenced through the theme URL, wherever the theme is installed.
	const php = markup
		.split( ASSET )
		.join( "<?php echo esc_url( get_theme_file_uri( 'assets/images/' ) ); ?>" )
		.split( ASSET_PATH )
		.join( "<?php echo esc_url( wp_make_link_relative( get_theme_file_uri( 'assets/images/' ) ) ); ?>" );
	// Check the markup as a site renders it (absolute theme URL, site-relative poster
	// paths), which is what the editor validates; the harness origin stands in for the site.
	const asSite = php
		.split( "<?php echo esc_url( get_theme_file_uri( 'assets/images/' ) ); ?>" )
		.join( ORIGIN + ASSET_PATH )
		.split( "<?php echo esc_url( wp_make_link_relative( get_theme_file_uri( 'assets/images/' ) ) ); ?>" )
		.join( ASSET_PATH );
	const siteProblems = invalid( asSite );
	if ( siteProblems.length ) {
		throw new Error( example.slug + ': invalid as rendered on a site: ' + siteProblems.join( ', ' ) );
	}
	const file = path.join( OUT, example.slug + '.php' );
	const content = header( example, requiredBlocks( blocks ) ) + '\n' + php + '\n';
	written.add( path.basename( file ) );
	if ( check ) {
		if ( ! fs.existsSync( file ) || fs.readFileSync( file, 'utf8' ) !== content ) {
			console.error( 'Out of date: ' + path.relative( ROOT, file ) );
			stale++;
		}
	} else {
		fs.writeFileSync( file, content );
	}
}
for ( const file of fs.readdirSync( OUT ) ) {
	if ( ! written.has( file ) ) {
		console.error( ( check ? 'Unexpected: ' : 'Removed: ' ) + file );
		if ( check ) {
			stale++;
		} else {
			fs.unlinkSync( path.join( OUT, file ) );
		}
	}
}
if ( stale ) {
	process.exit( 1 );
}
console.log( ( check ? 'Examples up to date: ' : 'Examples built: ' ) + examples.length );
